// t(lang, key, vars?) — looks up STRINGS[lang][key], falling back to English
// if the language or key is missing (e.g. a key added after a language was
// last touched), then substitutes any {token} placeholders from vars.
function t(lang, key, vars) {
  const table = STRINGS[lang] || STRINGS.en;
  let str = table[key];
  if (str === undefined) str = STRINGS.en[key];
  if (str === undefined) return key;
  if (vars) {
    Object.keys(vars).forEach((k) => {
      str = str.replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]);
    });
  }
  return str;
}
